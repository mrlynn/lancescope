# Front matter lives here rather than in the generated files, because the files are
# rewritten wholesale and anything hand-added to them would be lost on the next run.
PAGES = {
    "reference-configuration.md": (configuration_reference, dict(
        title="Configuration", order=1,
        summary="Every environment variable and settings field, and which one wins.")),
    "reference-query.md": (query_reference, dict(
        title="Query modes", order=2,
        summary="What a table can be asked, the access paths, and the limits.")),
    "reference-findings.md": (findings_reference, dict(
        title="Findings", order=3,
        summary="Every rule the console applies, and what each one checks.")),
    "reference-models.md": (models_reference, dict(
        title="Models and providers", order=4,
        summary="The registry: who serves what, what it costs, what it can do.")),
    "reference-mcp.md": (mcp_reference, dict(
        title="Agent tools", order=5,
        summary="The MCP tool set, and what the server tells a caller.")),
    "reference-http-api.md": (http_api, dict(
        title="HTTP API", order=6,
        summary="Every route, read from the server's own route table.")),
}


def front_matter(meta: dict) -> str:
    return (f"---\ntitle: {meta['title']}\nsection: Reference\n"
            f"order: {meta['order']}\nsummary: {meta['summary']}\n"
            f"generated: true\n---\n\n")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true",
                        help="fail if the committed files are out of date")
    args = parser.parse_args()

    GUIDE.mkdir(parents=True, exist_ok=True)
    stale = []
    for name, (build, meta) in PAGES.items():
        path = GUIDE / name
        fresh = front_matter(meta) + build().rstrip() + "\n"
        current = path.read_text() if path.exists() else ""
        if args.check:
            if current != fresh:
                stale.append(name)
        elif current != fresh:
            path.write_text(fresh)
            print(f"  wrote {path.relative_to(ROOT)}")

    if args.check and stale:
        print("These reference pages no longer match the code:")
        for name in stale:
            print(f"  {name}")
        print("\nRun `make docs`. Do not edit them by hand — the code is the source.")
        return 1
    if args.check:
        print(f"  {len(PAGES)} reference pages match the code")
    return 0


if __name__ == "__main__":
    sys.exit(main())
